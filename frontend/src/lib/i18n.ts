export type TranslationKey = keyof typeof DICTIONARY;

const normalizeLang = (lang: string | null | undefined): Lang =>
  lang === 'id' ? 'id' : DEFAULT_LANG;

/**
 * Looks up a translation key for the given language (falls back to English
 * for null/unset/unrecognized values). Supports simple {placeholder}
 * interpolation via the optional `vars` map.
 */
export const t = (
  key: TranslationKey,
  lang: string | null | undefined,
  vars?: Record<string, string | number>
): string => {
  const resolved = normalizeLang(lang);
  let text: string = DICTIONARY[key][resolved];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
};
