'use strict';
const { Resend } = require('resend');
const PDFDocument = require('pdfkit');

const resend = new Resend(process.env.RESEND_API_KEY);

// ── Generate PDF buffer from proposal data ────────────────
const generateProposalPDF = (proposal) => {
  return new Promise((resolve, reject) => {
    const doc    = new PDFDocument({ margin: 50, size: 'A4' });
    const chunks = [];

    doc.on('data',  chunk => chunks.push(chunk));
    doc.on('end',   ()    => resolve(Buffer.concat(chunks)));
    doc.on('error', err   => reject(err));

    const CYAN  = '#00e5ff';
    const DARK  = '#0a0a0a';
    const GRAY  = '#666666';
    const WHITE = '#ffffff';

    // Cover
    doc.rect(0, 0, doc.page.width, doc.page.height).fill(DARK);
    doc.fill(CYAN).fontSize(28).font('Helvetica-Bold')
      .text('THE TRIANGLE', 50, 80, { align: 'center' });
    doc.fill(WHITE).fontSize(14).font('Helvetica')
      .text('Quarterly System Proposal', 50, 120, { align: 'center' });
    doc.fill(GRAY).fontSize(11)
      .text(`Quarter: ${proposal.quarter}`, 50, 150, { align: 'center' });
    doc.fill(GRAY).fontSize(10)
      .text(`Generated: ${new Date(proposal.created_at).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}`, 50, 170, { align: 'center' });

    // Summary
    doc.moveDown(4);
    doc.fill(CYAN).fontSize(12).font('Helvetica-Bold').text('OVERALL ASSESSMENT');
    doc.moveDown(0.5);
    doc.fill(WHITE).fontSize(10).font('Helvetica')
      .text(proposal.theones_summary || 'No summary available.', { lineGap: 4 });

    const renderSection = (title, data, priority) => {
      if (!data) return;
      doc.addPage();
      doc.rect(0, 0, doc.page.width, doc.page.height).fill(DARK);

      const priorityColor = priority === 'high' ? '#ef4444'
        : priority === 'medium' ? '#f59e0b' : '#22c55e';

      doc.fill(CYAN).fontSize(14).font('Helvetica-Bold').text(title, 50, 60);
      doc.fill(priorityColor).fontSize(9).font('Helvetica')
        .text(`PRIORITY: ${(priority || 'low').toUpperCase()}`, 50, 82);

      doc.moveDown(1.5);
      doc.fill(CYAN).fontSize(10).font('Helvetica-Bold').text('OBSERVATIONS');
      doc.moveDown(0.4);
      (data.observations || []).forEach((obs, i) => {
        doc.fill(WHITE).fontSize(9).font('Helvetica')
          .text(`${i + 1}. ${obs}`, { lineGap: 3 });
        doc.moveDown(0.3);
      });

      doc.moveDown(0.8);
      doc.fill(CYAN).fontSize(10).font('Helvetica-Bold').text('RECOMMENDATIONS');
      doc.moveDown(0.4);
      (data.recommendations || []).forEach((rec, i) => {
        doc.fill(WHITE).fontSize(9).font('Helvetica')
          .text(`${i + 1}. ${rec}`, { lineGap: 3 });
        doc.moveDown(0.3);
      });
    };

    renderSection('1. SAFETY & CONDUCT',  proposal.safety_conduct, proposal.safety_conduct?.priority);
    renderSection('2. API & NEWS COLLECTION', proposal.api_news,   proposal.api_news?.priority);
    renderSection('3. BUG & FUNCTION',    proposal.bug_function,   proposal.bug_function?.priority);
    renderSection('4. USER FEEDBACK',     proposal.user_feedback,  proposal.user_feedback?.priority);

    // Footer page
    doc.addPage();
    doc.rect(0, 0, doc.page.width, doc.page.height).fill(DARK);
    doc.fill(GRAY).fontSize(9).font('Helvetica')
      .text('This proposal was generated by TheOnes and requires human review before any changes are applied.', 50, 200, { align: 'center', lineGap: 4 });
    doc.fill(GRAY).fontSize(9)
      .text('No AI system has write access to production. All approvals must be made by Leuenaar.', 50, 230, { align: 'center' });

    doc.end();
  });
};

// ── Send proposal via email ───────────────────────────────
const sendProposalEmail = async (proposal) => {
  try {
    const pdfBuffer = await generateProposalPDF(proposal);

    const priorityFlags = [
      proposal.safety_conduct?.priority === 'high'  ? 'Safety/Conduct: HIGH' : null,
      proposal.api_news?.priority       === 'high'  ? 'API/News: HIGH'       : null,
      proposal.bug_function?.priority   === 'high'  ? 'Bug/Function: HIGH'   : null,
    ].filter(Boolean);

    const subject = priorityFlags.length > 0
      ? `[The Triangle] Quarterly Proposal ${proposal.quarter} — ACTION REQUIRED`
      : `[The Triangle] Quarterly Proposal ${proposal.quarter}`;

    const htmlBody = `
      <div style="font-family: monospace; background: #0a0a0a; color: #ffffff; padding: 32px; max-width: 600px;">
        <h1 style="color: #00e5ff; font-size: 20px; margin-bottom: 4px;">THE TRIANGLE</h1>
        <p style="color: #666; font-size: 12px; margin-top: 0;">Quarterly System Proposal — ${proposal.quarter}</p>
        <hr style="border-color: #222; margin: 20px 0;" />
        <p style="font-size: 13px; line-height: 1.6; color: #ccc;">${proposal.theones_summary || 'No summary available.'}</p>
        <hr style="border-color: #222; margin: 20px 0;" />
        <table style="width: 100%; font-size: 11px;">
          <tr>
            <td style="color: #666; padding: 4px 0;">Safety & Conduct</td>
            <td style="color: ${proposal.safety_conduct?.priority === 'high' ? '#ef4444' : proposal.safety_conduct?.priority === 'medium' ? '#f59e0b' : '#22c55e'}; text-align: right; text-transform: uppercase;">${proposal.safety_conduct?.priority || 'low'}</td>
          </tr>
          <tr>
            <td style="color: #666; padding: 4px 0;">API & News Collection</td>
            <td style="color: ${proposal.api_news?.priority === 'high' ? '#ef4444' : proposal.api_news?.priority === 'medium' ? '#f59e0b' : '#22c55e'}; text-align: right; text-transform: uppercase;">${proposal.api_news?.priority || 'low'}</td>
          </tr>
          <tr>
            <td style="color: #666; padding: 4px 0;">Bug & Function</td>
            <td style="color: ${proposal.bug_function?.priority === 'high' ? '#ef4444' : proposal.bug_function?.priority === 'medium' ? '#f59e0b' : '#22c55e'}; text-align: right; text-transform: uppercase;">${proposal.bug_function?.priority || 'low'}</td>
          </tr>
          <tr>
            <td style="color: #666; padding: 4px 0;">User Feedback</td>
            <td style="color: ${proposal.user_feedback?.priority === 'high' ? '#ef4444' : proposal.user_feedback?.priority === 'medium' ? '#f59e0b' : '#22c55e'}; text-align: right; text-transform: uppercase;">${proposal.user_feedback?.priority || 'low'}</td>
          </tr>
        </table>
        <hr style="border-color: #222; margin: 20px 0;" />
        <p style="color: #666; font-size: 10px;">Full proposal attached as PDF. Review and approve via Admin Terminal.</p>
      </div>
    `;

    const { data, error } = await resend.emails.send({
      from:    'The Triangle <noreply@leuenaar.my.id>',
      to:      [process.env.OWNER_EMAIL],
      subject,
      html:    htmlBody,
      attachments: [{
        filename:    `proposal-${proposal.quarter}.pdf`,
        content:     pdfBuffer.toString('base64'),
        contentType: 'application/pdf',
      }],
    });

    if (error) throw error;

    console.log(`[ProposalDelivery] Email sent — id: ${data.id}`);
    return { status: 'success', emailId: data.id };

  } catch (err) {
    console.error('[ProposalDelivery] Email error:', err.message);
    return { status: 'error', message: err.message };
  }
};

module.exports = { generateProposalPDF, sendProposalEmail };